"""Generate dependency-free per-app launcher scripts.

The generated launcher is a tiny stdlib + ctypes script that is run by the
virtual environment's ``pythonw.exe``/``python.exe``.  It takes care of the
runtime half of taskbar grouping (setting the process AppUserModelID) and
turns otherwise-silent ``pythonw`` failures into a message box plus a log
file.
"""

import os
import re
import sys
from pathlib import Path
from typing import Optional


LAUNCHER_FILENAME = "launcher.py"
LOG_FILENAME = "pynstall.log"


_LAUNCHER_TEMPLATE = '''"""Generated by pynstall - do not edit by hand.

Runs the project's live entry point and reports failures instead of dying
silently under pythonw.exe.
"""

import ctypes
import sys
from pathlib import Path

APP_NAME = {APP_NAME}
APP_ID = {APP_ID}
ENTRY = {ENTRY}
ENTRY_IS_SCRIPT = {ENTRY_IS_SCRIPT}
PROJECT_DIR = {PROJECT_DIR}
PYTHON_EXE = {PYTHON_EXE}
LOG_PATH = {LOG_PATH}


def _show_error(message, title=None):
    """Show a Windows message box, falling back to stderr."""
    title = title or (APP_NAME + " - pynstall")
    try:
        ctypes.windll.user32.MessageBoxW(None, str(message), str(title), 0x10)
    except Exception:
        try:
            sys.stderr.write(str(message) + "\\n")
        except Exception:
            pass


def _append_log(text):
    """Append text to the pynstall log, ignoring logging failures."""
    try:
        path = Path(LOG_PATH)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "a", encoding="utf-8") as handle:
            handle.write(text)
            if not text.endswith("\\n"):
                handle.write("\\n")
    except Exception:
        pass


def _set_app_user_model_id():
    """Set the process AUMID so taskbar pinning groups correctly."""
    try:
        ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID(APP_ID)
    except Exception:
        pass


def _prepare_sys_path():
    """Make the project importable when the launcher lives outside it."""
    paths = [PROJECT_DIR]
    if ENTRY_IS_SCRIPT:
        paths.insert(0, str(Path(ENTRY).parent))

    for path in reversed(paths):
        if path and path not in sys.path:
            sys.path.insert(0, path)


def _run_entry_point():
    """Run the entry point the same way ``python -m`` or a script would."""
    import runpy

    if ENTRY_IS_SCRIPT:
        runpy.run_path(ENTRY, run_name="__main__")
    else:
        runpy.run_module(ENTRY, run_name="__main__", alter_sys=True)


def main():
    """Verify the environment, set the AUMID, then run the app."""
    exe = Path(PYTHON_EXE)
    if not exe.exists():
        message = (
            "Cannot start " + APP_NAME + ": the virtual environment Python "
            "executable was not found.\\n\\n"
            "Expected: " + str(exe) + "\\n\\n"
            "Recreate the virtual environment or reinstall the app with "
            "pynstall."
        )
        _append_log("\\n" + message + "\\n")
        _show_error(message)
        return 1

    _set_app_user_model_id()
    _prepare_sys_path()

    try:
        _run_entry_point()
    except SystemExit:
        raise
    except BaseException:
        import traceback

        tb = traceback.format_exc()
        summary = tb.strip().splitlines()[-1] if tb.strip() else "Unknown error"
        message = (
            "Error while running " + APP_NAME + ".\\n\\n"
            + summary + "\\n\\n"
            "Full traceback written to:\\n" + LOG_PATH
        )
        _append_log("\\n" + tb)
        _show_error(message)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


def _safe_dir_name(name: str) -> str:
    """Return a filesystem-safe directory name for an application name."""
    cleaned = re.sub(r'[<>:"/\\|?*\x00-\x1f]', "_", name).strip(" .")
    return cleaned or "pynstall-app"


def get_launcher_dir(app_name: str) -> Path:
    """Get the per-app data directory under ``%LOCALAPPDATA%``.

    Args:
        app_name: Display name of the application.

    Returns:
        Path to the per-app directory (not guaranteed to exist).
    """
    local_app_data = os.environ.get("LOCALAPPDATA")
    if local_app_data:
        root = Path(local_app_data)
    elif sys.platform == "win32":
        root = Path(os.environ.get("USERPROFILE", str(Path.home()))) / "AppData" / "Local"
    else:
        root = Path.home() / ".local" / "share"
    return root / _safe_dir_name(app_name)


def get_launcher_path(app_name: str) -> Path:
    """Get the path of the generated launcher for an application."""
    return get_launcher_dir(app_name) / LAUNCHER_FILENAME


def get_log_path(app_name: str) -> Path:
    """Get the path of the generated launcher log for an application."""
    return get_launcher_dir(app_name) / LOG_FILENAME


def build_launcher_source(
    app_name: str,
    entry: str,
    appid: str,
    python_exe: Path,
    entry_is_script: bool = False,
    log_path: Optional[Path] = None,
    project_dir: Optional[Path] = None,
) -> str:
    """Build the source code for a per-app launcher.

    Args:
        app_name: Display name of the application.
        entry: Module path (e.g. ``myapp.main``) or absolute script path.
        appid: AppUserModelID that is also stamped on the shortcut.
        python_exe: Virtual environment Python executable to verify at startup.
        entry_is_script: True when ``entry`` is a script path instead of a module.
        log_path: Override for the traceback log path.
        project_dir: Project root added to ``sys.path`` before importing.

    Returns:
        Launcher source code as a string.
    """
    if log_path is None:
        log_path = get_log_path(app_name)

    replacements = {
        "APP_NAME": repr(str(app_name)),
        "APP_ID": repr(str(appid)),
        "ENTRY": repr(str(entry)),
        "ENTRY_IS_SCRIPT": repr(bool(entry_is_script)),
        "PROJECT_DIR": repr("" if project_dir is None else str(project_dir)),
        "PYTHON_EXE": repr(str(python_exe)),
        "LOG_PATH": repr(str(log_path)),
    }

    return _LAUNCHER_TEMPLATE.format(**replacements)


def create_launcher(
    launcher_path: Path,
    app_name: str,
    entry: str,
    appid: str,
    python_exe: Path,
    entry_is_script: bool = False,
    log_path: Optional[Path] = None,
    project_dir: Optional[Path] = None,
) -> bool:
    """Write a generated launcher script to disk.

    Args:
        launcher_path: Destination path for the launcher ``.py`` file.
        app_name: Display name of the application.
        entry: Module path or absolute script path to run.
        appid: AppUserModelID to set on the process and the shortcut.
        python_exe: Virtual environment Python executable to verify.
        entry_is_script: True when ``entry`` is a script path.
        log_path: Override for the traceback log path.
        project_dir: Project root added to ``sys.path`` before importing.

    Returns:
        True if the launcher was written successfully.
    """
    launcher_path = Path(launcher_path)
    source = build_launcher_source(
        app_name=app_name,
        entry=entry,
        appid=appid,
        python_exe=python_exe,
        entry_is_script=entry_is_script,
        log_path=log_path,
        project_dir=project_dir,
    )

    try:
        launcher_path.parent.mkdir(parents=True, exist_ok=True)
        launcher_path.write_text(source, encoding="utf-8")
        return True
    except OSError as exc:
        print(f"Error creating launcher: {exc}")
        return False


def remove_launcher(launcher_path: Path) -> bool:
    """Delete a generated launcher file.

    Args:
        launcher_path: Path to the launcher to remove.

    Returns:
        True if the launcher was removed or did not exist.
    """
    launcher_path = Path(launcher_path)
    try:
        if launcher_path.exists():
            launcher_path.unlink()
        return True
    except OSError as exc:
        print(f"Error deleting launcher: {exc}")
        return False
